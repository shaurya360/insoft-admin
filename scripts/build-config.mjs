// Generates js/config.js (browser config) from .env or environment variables.
//   node scripts/build-config.mjs            -> writes js/config.js
//   node scripts/build-config.mjs dist       -> copies the site to dist/ and writes dist/js/config.js
//
// Only PUBLIC values go to the browser: the project URL and the anon/publishable key.
// The script refuses to continue if it is given a service-role / secret key.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function readDotEnv() {
  const file = path.join(root, '.env');
  if (!fs.existsSync(file)) return {};
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

const env = { ...readDotEnv(), ...process.env };
const url = (env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (env.SUPABASE_ANON_KEY || '').trim();

function fail(msg) {
  console.error('\n✗ ' + msg + '\n');
  process.exit(1);
}

if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url) && !/^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(url)) {
  fail('SUPABASE_URL is missing or invalid. Expected https://<project-ref>.supabase.co');
}
if (!key) fail('SUPABASE_ANON_KEY is missing.');
if (/^sb_secret_/.test(key)) fail('SUPABASE_ANON_KEY is a SECRET key. Use the anon / publishable key — never a secret key in the browser.');
if (key.split('.').length === 3) {
  try {
    const payload = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString('utf8'));
    if (payload.role === 'service_role') fail('SUPABASE_ANON_KEY is the service_role key. Use the anon key — never the service_role key in the browser.');
  } catch { /* not a JWT — fine */ }
}

const config = `// Generated by scripts/build-config.mjs — do not edit, do not commit.
// Public values only (Supabase URL + anon/publishable key). Data is protected by RLS.
window.APP_CONFIG = Object.freeze(${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key }, null, 2)});
`;

const outDir = process.argv[2] ? path.resolve(root, process.argv[2]) : null;
if (outDir) {
  fs.rmSync(outDir, { recursive: true, force: true });
  const include = ['index.html', 'login.html', 'dashboard.html', 'quotation.html', 'money.html', 'vendors.html', 'enquiries.html', 'logo.jpg', 'css', 'js'];
  for (const item of include) fs.cpSync(path.join(root, item), path.join(outDir, item), { recursive: true });
  fs.writeFileSync(path.join(outDir, 'js', 'config.js'), config);
  console.log(`✓ Site built to ${path.relative(root, outDir)}/`);
} else {
  fs.writeFileSync(path.join(root, 'js', 'config.js'), config);
  console.log('✓ js/config.js written');
}
